-- Part 2 of 2 of the migration-history baseline.
--
-- Creates the ~40 models that were added with `prisma db push` and never
-- recorded in migration history, and brings `second`'s tables up to date.
-- Ordered between `second` and `sync_schema_drift` on purpose: the drift
-- migration ALTERs tables/enums created here, so on a fresh database this
-- has to run before it. Excludes everything `sync_schema_drift` itself
-- creates (including AiJob.performanceFeedbackId and PipelineStage's
-- PERFORMANCE_FEEDBACK value).
--
-- Idempotent: every statement is guarded (IF NOT EXISTS, or a DO block that
-- swallows duplicate_object), so it is a no-op on a database already synced
-- via `db push` — e.g. production. The one column removal (Redirect.permanent)
-- copies its data into statusCode first and only runs if the column exists.
-- Caveat: IF NOT EXISTS skips a table that exists in an OLDER shape — always
-- run `prisma migrate diff --exit-code` afterwards. See docs/deployment.md
-- before applying this anywhere: test on staging first.
--
-- Generated by diffing a disposable database at `second`'s state against
-- prisma/schema.prisma, then removing the drift migration's statements.

