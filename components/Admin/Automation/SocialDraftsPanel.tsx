"use client";

import { useState } from "react";
import { Copy, Check } from "lucide-react";
import { dismissSocialDraftAction, listSocialDraftsAction } from "@/app/(admin)/actions/automation";

type Draft = Awaited<ReturnType<typeof listSocialDraftsAction>>[number];

function CopyButton({ text }: { text: string }) {
  const [copied, setCopied] = useState(false);
  return (
    <button
      type="button"
      onClick={async () => {
        await navigator.clipboard.writeText(text);
        setCopied(true);
        setTimeout(() => setCopied(false), 1500);
      }}
      className="flex items-center gap-1 text-xs text-brand-orange-deep dark:text-brand-orange-light hover:underline"
    >
      {copied ? <Check size={12} /> : <Copy size={12} />}
      {copied ? "Copied" : "Copy"}
    </button>
  );
}

export default function SocialDraftsPanel({ initialDrafts }: { initialDrafts: Draft[] }) {
  const [drafts, setDrafts] = useState(initialDrafts);

  const handleDismiss = async (id: string) => {
    setDrafts((prev) => prev.filter((d) => d.id !== id));
    await dismissSocialDraftAction(id);
  };

  if (drafts.length === 0) {
    return <p className="text-sm text-caption">No pending social drafts — these are generated by the &ldquo;Generate social draft&rdquo; automation action and never posted automatically; copy the text you want and post it yourself.</p>;
  }

  return (
    <div className="space-y-3">
      {drafts.map((draft) => (
        <div key={draft.id} className="bg-card border border-border rounded-lg p-4 space-y-3">
          <div className="flex items-start justify-between">
            <p className="font-medium text-foreground">{draft.content?.title ?? draft.contentId}</p>
            <button type="button" onClick={() => handleDismiss(draft.id)} className="text-xs text-caption hover:text-foreground">
              Dismiss
            </button>
          </div>
          <div className="space-y-1">
            <div className="flex items-center justify-between">
              <p className="text-xs font-semibold text-muted uppercase tracking-wide">LinkedIn</p>
              <CopyButton text={draft.linkedinText} />
            </div>
            <p className="text-sm text-foreground whitespace-pre-wrap bg-background border border-border rounded-lg p-2">{draft.linkedinText}</p>
          </div>
          <div className="space-y-1">
            <div className="flex items-center justify-between">
              <p className="text-xs font-semibold text-muted uppercase tracking-wide">X / Twitter</p>
              <CopyButton text={draft.twitterText} />
            </div>
            <p className="text-sm text-foreground whitespace-pre-wrap bg-background border border-border rounded-lg p-2">{draft.twitterText}</p>
          </div>
        </div>
      ))}
    </div>
  );
}
